CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('admin', 'editor', 'viewer')),
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    passwordless INTEGER NOT NULL DEFAULT 0 CHECK(passwordless IN (0,1) AND (passwordless=0 OR role='viewer'))
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_casefold ON users(lower(username));
CREATE TABLE IF NOT EXISTS pages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 200),
    url TEXT NOT NULL,
    profile_id TEXT NOT NULL UNIQUE,
    target INTEGER NOT NULL CHECK(target BETWEEN 0 AND 1000000),
    active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS seed_registry (
    seed_key TEXT PRIMARY KEY,
    page_id BIGINT NOT NULL REFERENCES pages(id)
);
CREATE TABLE IF NOT EXISTS reports (
    date TEXT PRIMARY KEY,
    revision INTEGER NOT NULL DEFAULT 1,
    updated_by BIGINT REFERENCES users(id),
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS report_rows (
    report_date TEXT NOT NULL REFERENCES reports(date),
    page_id BIGINT NOT NULL REFERENCES pages(id),
    page_name TEXT NOT NULL,
    profile_url TEXT NOT NULL,
    target INTEGER NOT NULL CHECK(target BETWEEN 0 AND 1000000),
    actual INTEGER NOT NULL DEFAULT 0 CHECK(actual BETWEEN 0 AND 1000000),
    PRIMARY KEY(report_date,page_id)
);
CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    csrf_token TEXT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS login_limits (
    client_key TEXT PRIMARY KEY,
    attempts INTEGER NOT NULL,
    started_at BIGINT NOT NULL
);
